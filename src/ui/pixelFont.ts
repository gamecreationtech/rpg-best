export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** One dot of space between letters, one row below for descenders. */
const ADVANCE = GLYPH_W + 1;
const LINE_H = GLYPH_H + 2;

function glyph(ch: string): string[] {
  return RAW[ch] ?? RAW[ch.toUpperCase()] ?? RAW['?']!;
}

export function textWidth(text: string): number {
  return text.length ? text.length * ADVANCE - 1 : 0;
}

/** Word-wraps text to at most `maxChars` letters per line. Existing newlines are kept. */
export function wrap(text: string, maxChars: number): string[] {
  const lines: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (line && line.length + 1 + word.length > maxChars) {
        lines.push(line);
        line = word;
      } else line = line ? `${line} ${word}` : word;
    }
    lines.push(line);
  }
  return lines;
}

/** Draws lines of text into a context at 1 dot per pixel. */
export function drawLines(ctx: CanvasRenderingContext2D, lines: string[], color: string, x = 0, y = 0): void {
  ctx.fillStyle = color;
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li]!;
    const ty = y + li * LINE_H;
    for (let i = 0; i < line.length; i++) {
      const g = glyph(line[i]!);
      const gx = x + i * ADVANCE;
      for (let r = 0; r < GLYPH_H; r++) {
        const row = g[r]!;
        for (let c = 0; c < GLYPH_W; c++) if (row[c] === '#') ctx.fillRect(gx + c, ty + r, 1, 1);
      }
    }
  }
}

export interface TextOptions {
  color?: string;
  /** Whole-number upscale; 2 matches the game frame on most desktops. */
  scale?: number;
  /** Wrap at this many letters per line. */
  maxChars?: number;
  /** Extra class on the element. */
  cls?: string;
}

/**
 * A block of pixel text as a canvas element sized in CSS to `scale` times its
 * dots. The element is inline-block so it sits in flex rows like a label.
 */
export function pxText(text: string, opts: TextOptions = {}): HTMLCanvasElement {
  const scale = opts.scale ?? 2;
  const lines = opts.maxChars ? wrap(text, opts.maxChars) : text.split('\n');
  const w = Math.max(1, ...lines.map(textWidth));
  const hgt = lines.length * LINE_H - 1;
  const c = document.createElement('canvas');
  c.className = 'px' + (opts.cls ? ' ' + opts.cls : '');
  c.width = w;
  c.height = hgt;
  c.style.width = `${w * scale}px`;
  c.style.height = `${hgt * scale}px`;
  drawLines(c.getContext('2d')!, lines, opts.color ?? '#d9dce6');
  c.dataset.text = text;
  return c;
}
